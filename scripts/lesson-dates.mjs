// Writes src/lib/lesson-dates.ts: { "category/slug": [published, updated] } from git history.
// Run locally (`node scripts/lesson-dates.mjs`) after committing lesson edits: Vercel builds from a
// shallow clone, so these dates can't be computed at build time.
// Commits touching more than SWEEP_LIMIT lesson files are site-wide sweeps (link fixes, formatting),
// not content updates, so they don't move a lesson's "updated" date.
import { execFileSync } from "node:child_process";
import { existsSync, writeFileSync } from "node:fs";

const SWEEP_LIMIT = 100;
const log = execFileSync("git", ["log", "--format=@%cs", "--name-only", "--", "src/content"], {
  encoding: "utf8",
  maxBuffer: 256 * 1024 * 1024,
});

const dates = {};
for (const block of log.split("@").slice(1)) {
  const [date, ...files] = block.trim().split("\n");
  const lessons = files
    .map((f) => f.trim().match(/^src\/content\/([^/]+\/[^/]+)\.mdx$/)?.[1])
    .filter(Boolean);
  const sweep = lessons.length > SWEEP_LIMIT;
  for (const id of lessons) {
    // git log runs newest first: the last date seen is the first commit.
    const d = (dates[id] ??= { published: date, updated: null });
    d.published = date;
    if (!sweep && !d.updated) d.updated = date;
  }
}

const rows = Object.keys(dates)
  .filter((id) => existsSync(`src/content/${id}.mdx`)) // drop lessons deleted since
  .sort()
  .map((id) => `  "${id}": ["${dates[id].published}", "${dates[id].updated ?? dates[id].published}"],`);
writeFileSync(
  "src/lib/lesson-dates.ts",
  `// Generated by scripts/lesson-dates.mjs from git history. Do not edit by hand.\n` +
    `// [datePublished, dateModified] per "category/slug" (the lesson's MDX path).\n` +
    `export const LESSON_DATES: Record<string, [string, string]> = {\n${rows.join("\n")}\n};\n`,
);
console.log(`wrote ${rows.length} lesson dates`);
